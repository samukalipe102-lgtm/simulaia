-- Simula Escola IA — persistent schema (SQLite)
-- All email data references REAL Gmail identifiers (threadId, messageId)
-- while request content itself is clearly flagged as fictitious/simulated.

PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;

-- Admin users (control access to the whole system).
CREATE TABLE IF NOT EXISTS users (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  email         TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'admin',
  created_at    TEXT NOT NULL DEFAULT (datetime('now'))
);

-- School services the admin enables; only these can be referenced by the AI.
CREATE TABLE IF NOT EXISTS services (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  name        TEXT NOT NULL,
  category    TEXT NOT NULL,              -- declaracao | historico | documento | esclarecimento
  description TEXT,
  enabled     INTEGER NOT NULL DEFAULT 1,
  created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Fictitious profiles the AI uses as senders of simulated requests.
CREATE TABLE IF NOT EXISTS profiles (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  name        TEXT NOT NULL,              -- always flagged fictitious
  role        TEXT NOT NULL,              -- responsavel | professor | coordenador | funcionario
  context     TEXT,                       -- extra flavor used by the generator
  fictitious  INTEGER NOT NULL DEFAULT 1,
  enabled     INTEGER NOT NULL DEFAULT 1,
  created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Gmail account connection (stores OAuth tokens — BACKEND ONLY, never sent to client).
CREATE TABLE IF NOT EXISTS gmail_accounts (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  email         TEXT,
  access_token  TEXT,
  refresh_token TEXT,
  scope         TEXT,
  token_type    TEXT,
  expiry_date   INTEGER,
  connected     INTEGER NOT NULL DEFAULT 0,
  last_error    TEXT,
  updated_at    TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Simulated school requests generated by the AI.
CREATE TABLE IF NOT EXISTS requests (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  public_id     TEXT UNIQUE NOT NULL,     -- human-friendly identifier e.g. SIM-2026-0001
  subject       TEXT NOT NULL,
  body          TEXT NOT NULL,
  category      TEXT NOT NULL,
  service_id    INTEGER,
  profile_id    INTEGER,
  profile_name  TEXT NOT NULL,            -- snapshot of fictitious sender
  profile_role  TEXT NOT NULL,
  recipient     TEXT,                     -- authorized destination mailbox
  status        TEXT NOT NULL DEFAULT 'generated',
    -- generated | scheduled | sending | sent | awaiting_reply | replied
    -- | awaiting_approval | completed | paused | error
  fictitious    INTEGER NOT NULL DEFAULT 1,
  scheduled_at  TEXT,
  sent_at       TEXT,
  attempts      INTEGER NOT NULL DEFAULT 0,
  last_error    TEXT,
  gmail_thread_id  TEXT,                  -- REAL Gmail thread id once sent
  gmail_message_id TEXT,                  -- REAL Gmail message id once sent
  automation_id INTEGER,
  -- Conversation lifecycle (end-to-end automation):
  conversation_state TEXT NOT NULL DEFAULT 'open',
    -- open | awaiting_info | needs_followup | resolved | closed | needs_admin
  followup_count INTEGER NOT NULL DEFAULT 0,  -- follow-ups already sent
  max_followups  INTEGER NOT NULL DEFAULT 3,  -- cap of follow-ups per conversation
  last_classification TEXT,                   -- latest AI classification of a reply
  created_at    TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at    TEXT NOT NULL DEFAULT (datetime('now')),
  FOREIGN KEY (service_id) REFERENCES services(id),
  FOREIGN KEY (profile_id) REFERENCES profiles(id)
);

-- Chronological messages inside a request's conversation (both directions).
CREATE TABLE IF NOT EXISTS messages (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  request_id    INTEGER NOT NULL,
  direction     TEXT NOT NULL,            -- outbound | inbound
  author        TEXT,                     -- fictitious profile name or real responder email
  subject       TEXT,
  body          TEXT,
  gmail_message_id TEXT,                  -- REAL Gmail message id
  gmail_thread_id  TEXT,
  approval_status TEXT,                   -- null | pending | approved | rejected | sent
  is_followup   INTEGER NOT NULL DEFAULT 0,
  classification TEXT,                    -- AI classification (for inbound replies)
  created_at    TEXT NOT NULL DEFAULT (datetime('now')),
  FOREIGN KEY (request_id) REFERENCES requests(id) ON DELETE CASCADE
);

-- Automation / scheduling configurations.
CREATE TABLE IF NOT EXISTS automations (
  id                INTEGER PRIMARY KEY AUTOINCREMENT,
  name              TEXT NOT NULL,
  status            TEXT NOT NULL DEFAULT 'paused',  -- active | paused
  max_per_day       INTEGER NOT NULL DEFAULT 5,
  interval_minutes  INTEGER NOT NULL DEFAULT 30,     -- min minutes between sends
  allowed_days      TEXT NOT NULL DEFAULT '1,2,3,4,5', -- 0=Sun..6=Sat
  start_hour        INTEGER NOT NULL DEFAULT 8,
  end_hour          INTEGER NOT NULL DEFAULT 18,
  categories        TEXT NOT NULL DEFAULT '',         -- comma list; empty = all enabled
  profile_ids       TEXT NOT NULL DEFAULT '',         -- comma list; empty = all enabled
  duration_days     INTEGER NOT NULL DEFAULT 7,
  recipient         TEXT,                             -- authorized destination
  require_approval  INTEGER NOT NULL DEFAULT 1,
  max_attempts      INTEGER NOT NULL DEFAULT 3,
  auto_followup     INTEGER NOT NULL DEFAULT 0,  -- send follow-ups automatically
  max_followups_per_conversation INTEGER NOT NULL DEFAULT 3,
  sent_today        INTEGER NOT NULL DEFAULT 0,
  sent_today_date   TEXT,
  last_run_at       TEXT,
  next_run_at       TEXT,
  starts_at         TEXT,
  ends_at           TEXT,
  created_at        TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at        TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Append-only activity / audit log and failure registry.
CREATE TABLE IF NOT EXISTS activity_log (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  level       TEXT NOT NULL DEFAULT 'info',  -- info | warn | error
  category    TEXT,                          -- scheduler | gmail | auth | automation | ai
  message     TEXT NOT NULL,
  request_id  INTEGER,
  automation_id INTEGER,
  created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Global system settings (single row id=1).
CREATE TABLE IF NOT EXISTS settings (
  id                 INTEGER PRIMARY KEY CHECK (id = 1),
  emergency_stop     INTEGER NOT NULL DEFAULT 0,  -- 1 = all automations halted
  test_mode          INTEGER NOT NULL DEFAULT 1,
  authorized_recipient TEXT,
  -- Google OAuth credentials configurable from the UI (desktop mode has no
  -- terminal to edit .env). Falls back to env vars when empty. Stored only in
  -- the local backend database.
  google_client_id     TEXT,
  google_client_secret TEXT,
  -- Full-automation controls:
  setup_completed      INTEGER NOT NULL DEFAULT 0,  -- single initial setup done
  auto_mode            INTEGER NOT NULL DEFAULT 0,  -- end-to-end automatic flow on
  auto_followup_approved INTEGER NOT NULL DEFAULT 0,-- admin authorized auto-send of follow-ups
  poll_interval_minutes  INTEGER NOT NULL DEFAULT 2,-- Gmail reply polling interval
  updated_at         TEXT NOT NULL DEFAULT (datetime('now'))
);

-- ============================================================
-- EduGestão — plataforma de atendimento escolar
-- ============================================================

-- Responsáveis (guardians). Dados mínimos; sem inventar e-mail/telefone/endereço.
CREATE TABLE IF NOT EXISTS guardians (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  name        TEXT NOT NULL,
  email       TEXT,                         -- opcional; nunca inventado
  phone       TEXT,                         -- opcional
  created_at  TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (name)
);

-- Alunos (students), vinculados a um responsável.
CREATE TABLE IF NOT EXISTS students (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  name        TEXT NOT NULL,
  guardian_id INTEGER,
  enrollment  TEXT,                         -- matrícula (opcional; nunca inventada)
  created_at  TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (name),
  FOREIGN KEY (guardian_id) REFERENCES guardians(id)
);

-- Catálogo de processos escolares administrativos.
CREATE TABLE IF NOT EXISTS processes (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  code            TEXT UNIQUE NOT NULL,     -- ex.: declaracao_matricula
  name            TEXT NOT NULL,
  category        TEXT NOT NULL,            -- declaracao | historico | documento | esclarecimento | cadastro | transferencia | encaminhamento
  description     TEXT,
  requirements    TEXT,                     -- requisitos (texto)
  steps           TEXT,                     -- etapas (texto)
  responsible_sector TEXT,                  -- setor responsável
  sla_days        INTEGER DEFAULT 5,        -- prazo configurável (dias)
  response_template TEXT,                   -- modelo de resposta
  completion_criteria TEXT,                 -- critérios de conclusão
  enabled         INTEGER NOT NULL DEFAULT 1,
  created_at      TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Assinaturas institucionais configuráveis por setor.
CREATE TABLE IF NOT EXISTS signatures (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  sector      TEXT UNIQUE NOT NULL,         -- ex.: atendimento | secretaria | coordenacao | direcao
  display_name TEXT NOT NULL,               -- ex.: Atendimento Escolar
  body        TEXT NOT NULL,                -- texto da assinatura (multi-linha)
  is_default  INTEGER NOT NULL DEFAULT 0,
  enabled     INTEGER NOT NULL DEFAULT 1,
  created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);
